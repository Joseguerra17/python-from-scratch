def suma():
    print("-- CALCULADORA | SUMA --")
    num1 = int(input("Escribe un Numero: "))
    num2 = int(input("Escribe tu Segundo Numero: "))
    calculo = num1 + num2
    print(f"EL RESULTADO ES: {calculo}")
    return calculo

